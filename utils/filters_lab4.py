# ---------- вспомогательное ----------

# Индексы строк (или столбцов) для дополнения краёв повтором крайнего пикселя
def _edge_indices(n, before, after):
    # Перебираем номера от -before до n+after-1; вылезающие за край прижимаем к 0 или n-1
    return [min(max(i, 0), n - 1) for i in range(-before, n + after)]


# Дополнить изображение полями: pad_y = (сверху, снизу), pad_x = (слева, справа)
def pad_edge(arr, pad_y, pad_x):
    # Высота и ширина исходного изображения
    h, w = arr.shape[:2]
    # Номера строк нового изображения (крайние строки повторяются)
    rows = _edge_indices(h, pad_y[0], pad_y[1])
    # Номера столбцов нового изображения (крайние столбцы повторяются)
    cols = _edge_indices(w, pad_x[0], pad_x[1])
    # Собираем изображение из строк, затем из столбцов в нужном порядке
    return arr[rows][:, cols]


# Перевод результата в пиксели 0..255 (uint8)
def to_uint8(arr):
    # Копия во float32, чтобы не портить исходный массив
    out = arr.astype(np.float32)
    # Отрицательные значения обрезаем до 0
    out[out < 0] = 0
    # Значения больше 255 обрезаем до 255
    out[out > 255] = 255
    # Округляем (+0.5 и отбрасывание дробной части) и приводим к uint8
    return (out + 0.5).astype(np.uint8)


# Яркость с плавающей точкой: Y = 0.299 R + 0.587 G + 0.114 B
def grayscale(img) -> np.ndarray:
    # Переводим во float32 для точных вычислений
    arr = img.astype(np.float32)
    # Если изображение уже ч/б, возвращаем как есть
    if arr.ndim == 2:
        # Ч/б изображение — без изменений
        return arr
    # Взвешенная сумма каналов R, G, B
    return 0.299 * arr[:, :, 0] + 0.587 * arr[:, :, 1] + 0.114 * arr[:, :, 2]


# Линейное растяжение диапазона [min, max] -> [0, 255]
def stretch(arr):
    # Минимальное значение в массиве
    mn = float(arr.min())
    # Максимальное значение в массиве
    mx = float(arr.max())
    # Если все значения одинаковые, растягивать нечего
    if mx - mn < 1e-12:
        # Возвращаем нулевое изображение того же размера
        return np.zeros(arr.shape, dtype=np.float32)
    # Сдвигаем минимум в 0 и масштабируем максимум в 255
    return (arr - mn) * (255.0 / (mx - mn))


# ---------- свёртка ----------

# Свёртка изображения (ч/б или RGB) с ядром произвольного размера kh×kw
def convolve(arr: np.ndarray, kernel) -> np.ndarray:
    # Все вычисления — с плавающей точкой
    arr = arr.astype(np.float32)
    # Высота ядра (число строк)
    kh = len(kernel)
    # Ширина ядра (число столбцов)
    kw = len(kernel[0])
    # Высота и ширина изображения
    h, w = arr.shape[:2]
    # Координаты центра ядра
    cy, cx = kh // 2, kw // 2
    # Дополняем края, чтобы окно не выходило за изображение
    pad = pad_edge(arr, (cy, kh - 1 - cy), (cx, kw - 1 - cx))
    # Результат: сначала нули, будем накапливать сумму
    out = np.zeros(arr.shape, dtype=np.float32)
    # Перебираем строки ядра
    for i in range(kh):
        # Перебираем столбцы ядра
        for j in range(kw):
            # Берём элемент отражённого ядра (свёртка, а не корреляция)
            k = float(kernel[kh - 1 - i][kw - 1 - j])
            # Нулевой коэффициент ничего не добавит — пропускаем
            if k == 0.0:
                # Переходим к следующему элементу ядра
                continue
            # Прибавляем всё изображение, сдвинутое на (i, j) и умноженное на k
            out += k * pad[i:i + h, j:j + w]
    # Возвращаем результат свёртки (float32, может быть < 0 и > 255)
    return out


# Свёртка с сепарабельным ядром K = v · vᵀ как две одномерные
def convolve_separable(arr: np.ndarray, kernel_1d) -> np.ndarray:
    # Сначала свёртка по строкам ядром-строкой 1×n
    tmp = convolve(arr, [list(kernel_1d)])
    # Затем свёртка по столбцам ядром-столбцом n×1
    return convolve(tmp, [[v] for v in kernel_1d])


# Сумма всех элементов матрицы (масштабный коэффициент)
def kernel_sum(kernel):
    # Начальное значение суммы
    total = 0.0
    # Перебираем строки матрицы
    for row in kernel:
        # Перебираем элементы строки
        for v in row:
            # Добавляем элемент к сумме
            total += v
    # Возвращаем сумму
    return total


# Применить матрицу к изображению; возвращает (изображение uint8, делитель)
def apply_kernel(img, kernel, normalize, use_abs, add128):
    # По умолчанию не делим
    divisor = 1.0
    # Если включена галочка «Нормализация»
    if normalize:
        # Считаем сумму элементов матрицы
        s = kernel_sum(kernel)
        # Делим, только если сумма не ноль (у Собеля и Лапласа она 0)
        if abs(s) > 1e-9:
            # Делитель = сумма элементов
            divisor = s
    # Делим каждый элемент матрицы на делитель
    k = [[v / divisor for v in row] for row in kernel]
    # Выполняем свёртку
    res = convolve(img, k)
    # Если включена галочка «По модулю»
    if use_abs:
        # Отрицательные отклики становятся положительными
        res = np.abs(res)
    # Если включена галочка «+128»
    if add128:
        # Сдвигаем ноль в серый цвет, чтобы были видны отрицательные отклики
        res = res + 128.0
    # Обрезаем до 0..255 и возвращаем вместе с делителем
    return to_uint8(res), divisor


# Разбор матрицы n×n из текста (числа через пробел, запятую, ; или с новой строки)
def parse_kernel(text):
    # Перебираем все допустимые разделители
    for sep in (",", ";", "\t", "\n"):
        # Заменяем разделитель на пробел
        text = text.replace(sep, " ")
    # Делим по пробелам и выбрасываем пустые куски
    tokens = [t for t in text.split(" ") if t]
    # Если ничего не введено
    if not tokens:
        # Сообщаем об ошибке
        raise ValueError("Матрица пустая")
    # Список чисел матрицы
    values = []
    # Перебираем введённые куски текста
    for t in tokens:
        # Пробуем перевести кусок в число
        try:
            # Добавляем число в список
            values.append(float(t))
        # Если это не число
        except ValueError:
            # Сообщаем, какой кусок не удалось разобрать
            raise ValueError(f"«{t}» — не число")
    # Размер матрицы — целый корень из количества чисел
    n = math.isqrt(len(values))
    # Если количество чисел не является квадратом
    if n * n != len(values):
        # Сообщаем об ошибке
        raise ValueError(
            # Текст ошибки с количеством введённых чисел
            f"Введено {len(values)} чисел — это не квадрат n×n"
        )
    # Нарезаем список на n строк по n чисел
    return [values[r * n:(r + 1) * n] for r in range(n)]


# Матрица -> текст для поля ввода
def format_kernel(kernel):
    # Список строк текста
    lines = []
    # Перебираем строки матрицы
    for row in kernel:
        # Числа строки через пробел (без лишних нулей)
        lines.append(" ".join(f"{v:g}" for v in row))
    # Склеиваем строки через перевод строки
    return "\n".join(lines)


# ---------- ядра ----------

# Одномерное ядро усреднения: n одинаковых весов 1/n
def box_kernel_1d(n):
    # Список из n элементов, каждый 1/n
    return [1.0 / n] * n


# Одномерное ядро Гаусса из n элементов (n нечётное), сумма = 1
def gauss_kernel_1d(n, sigma):
    # Половина размера ядра (расстояние от центра до края)
    half = n // 2
    # Значения exp(-i² / 2σ²) для i от -half до half
    vals = [math.exp(-(i * i) / (2.0 * sigma * sigma)) for i in range(-half, half + 1)]
    # Сумма значений
    s = sum(vals)
    # Нормируем, чтобы сумма весов была ровно 1
    return [v / s for v in vals]


# Нечётный размер ядра Гаусса по правилу 3σ
def gauss_size(sigma):
    # 3σ в каждую сторону + центральный элемент
    return 2 * int(math.ceil(3.0 * sigma)) + 1


# Внешнее произведение вектора на себя: матрица v · vᵀ
def _outer(v):
    # Элемент (a, b) = a * b
    return [[a * b for b in v] for a in v]


