# ---------- размытие и High-pass ----------

# Размытие: method = "box" (усреднение) или "gauss" (Гаусс), размер n×n
def blur(arr, method, n, sigma=1.0):
    # Если выбран Гаусс
    if method == "gauss":
        # Одномерное ядро Гаусса
        k = gauss_kernel_1d(n, sigma)
    # Иначе — усреднение
    else:
        # Одномерное ядро усреднения
        k = box_kernel_1d(n)
    # Оба ядра сепарабельны — считаем двумя одномерными свёртками
    return convolve_separable(arr, k)


# Способ «+128»: ноль становится серым
NEG_ADD128 = "+128"
# Способ «по модулю»: знак отбрасывается
NEG_ABS = "По модулю"
# Способ «растяжение»: весь диапазон переводится в 0..255
NEG_STRETCH = "Растяжение min..max"
# Способ «обрезка»: отрицательные значения становятся 0
NEG_CLIP = "Обрезка до 0"
# Список способов для выпадающего списка в окне
NEG_MODES = [NEG_ADD128, NEG_ABS, NEG_STRETCH, NEG_CLIP]


# Исправление отрицательной яркости выбранным способом
def fix_negative(arr, mode):
    # Способ «+128»
    if mode == NEG_ADD128:
        # Прибавляем 128 ко всем значениям
        return arr + 128.0
    # Способ «по модулю»
    if mode == NEG_ABS:
        # Берём модуль каждого значения
        return np.abs(arr)
    # Способ «растяжение»
    if mode == NEG_STRETCH:
        # Растягиваем [min, max] в [0, 255]
        return stretch(arr)
    # Способ «обрезка»: ничего не делаем, обрезка выполнится в to_uint8
    return arr


# High-pass: ВЧ = ИСХ − c · РАЗМ; возвращает (размытое, высокочастотное)
def high_pass(img, method, n, sigma, c, neg_mode):
    # Исходное изображение во float32
    orig = img.astype(np.float32)
    # Размытое изображение (низкие частоты)
    blurred = blur(orig, method, n, sigma)
    # Вычитаем размытое с коэффициентом c (остаются высокие частоты)
    hf = orig - c * blurred
    # Переводим оба изображения в 0..255, у ВЧ исправляем отрицательные значения
    return to_uint8(blurred), to_uint8(fix_negative(hf, neg_mode))


# ---------- границы: оператор Собеля / Превитта ----------

# Модуль градиента |∇I| и (если задан порог) бинарная карта границ
def edges(img, operator="Sobel", pre_blur_sigma=0.0, threshold=0):
    # Переводим изображение в яркость
    g = grayscale(img)
    # Если задано предварительное размытие
    if pre_blur_sigma > 0:
        # Размываем Гауссом, чтобы шум не давал ложных границ
        g = blur(g, "gauss", gauss_size(pre_blur_sigma), pre_blur_sigma)
    # Выбираем пару ядер: Собель или Превитт
    kx, ky = (SOBEL_X, SOBEL_Y) if operator == "Sobel" else (PREWITT_X, PREWITT_Y)
    # Производная по x (реагирует на вертикальные границы)
    gx = convolve(g, kx)
    # Производная по y (реагирует на горизонтальные границы)
    gy = convolve(g, ky)
    # Модуль градиента: sqrt(Gx² + Gy²)
    mag = np.sqrt(gx * gx + gy * gy)
    # Максимальное значение модуля
    mx = float(mag.max())
    # Если на изображении есть хоть один перепад
    if mx > 0:
        # Масштабируем модуль в диапазон 0..255
        mag = mag * (255.0 / mx)
    # Бинарной карты пока нет
    binary = None
    # Если задан порог
    if threshold > 0:
        # Чёрное изображение того же размера
        binary = np.zeros(mag.shape, dtype=np.uint8)
        # Пиксели с модулем градиента не меньше порога — белые (граница)
        binary[mag >= threshold] = 255
    # Возвращаем модуль градиента и бинарную карту
    return to_uint8(mag), binary


# ---------- углы: детектор Харриса ----------

# Максимум в окне (2r+1)×(2r+1) — раздельно по строкам и по столбцам
def max_filter(arr, r):
    # Высота и ширина массива
    h, w = arr.shape[:2]
    # Дополняем сверху и снизу на r строк
    pad = pad_edge(arr, (r, r), (0, 0))
    # Начинаем с первого сдвига по вертикали
    m = pad[0:h].copy()
    # Перебираем остальные 2r сдвигов по вертикали
    for i in range(1, 2 * r + 1):
        # Поэлементный максимум с очередным сдвигом
        m = np.maximum(m, pad[i:i + h])
    # Дополняем слева и справа на r столбцов
    pad = pad_edge(m, (0, 0), (r, r))
    # Начинаем с первого сдвига по горизонтали
    out = pad[:, 0:w].copy()
    # Перебираем остальные 2r сдвигов по горизонтали
    for j in range(1, 2 * r + 1):
        # Поэлементный максимум с очередным сдвигом
        out = np.maximum(out, pad[:, j:j + w])
    # Возвращаем максимум по окну для каждого пикселя
    return out


# Детектор углов Харриса; возвращает (ys, xs, карта отклика R)
def harris(img, k=0.04, sigma=1.5, rel_threshold=0.01, nms_radius=4):
    # Переводим изображение в яркость
    g = grayscale(img)
    # Производная по x (Собель, деление на 8 — сумма модулей весов)
    ix = convolve(g, SOBEL_X) / 8.0
    # Производная по y (Собель)
    iy = convolve(g, SOBEL_Y) / 8.0
    # Окно Гаусса для суммирования по окрестности
    win = gauss_kernel_1d(gauss_size(sigma), sigma)
    # Элемент матрицы структуры Ix², сглаженный окном
    ixx = convolve_separable(ix * ix, win)
    # Элемент матрицы структуры Iy², сглаженный окном
    iyy = convolve_separable(iy * iy, win)
    # Элемент матрицы структуры Ix·Iy, сглаженный окном
    ixy = convolve_separable(ix * iy, win)
    # След матрицы M = λ1 + λ2
    trace = ixx + iyy
    # Отклик R = det(M) − k·trace(M)²
    r = ixx * iyy - ixy * ixy - k * trace * trace
    # Максимальный отклик на изображении
    r_max = float(r.max())
    # Если положительного отклика нет — углов нет
    if r_max <= 0:
        # Пустые списки координат и карта отклика
        return np.array([], dtype=int), np.array([], dtype=int), r
    # Максимум отклика в окрестности каждого пикселя
    local_max = max_filter(r, nms_radius)
    # Угол: локальный максимум и отклик выше порога
    mask = (r >= local_max) & (r > rel_threshold * r_max)
    # Координаты найденных углов
    ys, xs = np.nonzero(mask)
    # Возвращаем координаты и карту отклика
    return ys, xs, r


# Карта отклика Харриса для показа на экране
def response_to_image(r):
    # Копия карты отклика
    pos = r.copy()
    # Отрицательные значения (границы) убираем
    pos[pos < 0] = 0
    # Максимальный положительный отклик
    mx = float(pos.max())
    # Если положительных значений нет
    if mx <= 0:
        # Возвращаем чёрное изображение
        return np.zeros(r.shape, dtype=np.uint8)
    # Нормируем и берём корень 4-й степени, чтобы были видны и слабые углы
    return to_uint8(255.0 * (pos / mx) ** 0.25)


# Нарисовать крестики в точках (ys, xs) на копии изображения
def draw_crosses(img, ys, xs, size=4, color=(255, 0, 0)):
    # Копия, чтобы не испортить исходное изображение
    out = img.copy()
    # Если изображение ч/б
    if out.ndim == 2:
        # Делаем из него трёхканальное, чтобы рисовать цветом
        out = np.stack([out, out, out], axis=-1)
    # Высота и ширина изображения
    h, w = out.shape[:2]
    # Перебираем смещения от -size до size
    for d in range(-size, size + 1):
        # Столбцы горизонтальной перекладины (не выходя за изображение)
        cx = np.minimum(np.maximum(xs + d, 0), w - 1)
        # Строки вертикальной перекладины (не выходя за изображение)
        cy = np.minimum(np.maximum(ys + d, 0), h - 1)
        # Рисуем точку горизонтальной перекладины
        out[ys, cx] = color
        # Рисуем точку вертикальной перекладины
        out[cy, xs] = color
    # Возвращаем изображение с крестиками
    return out
